"""What the AI workers may see of a patient: the HIPAA Safe Harbor boundary (164.514(b)).

Pure rules (no I/O). ``infrastructure/orthanc/deidentify.py`` applies them to every DICOM
file a pipeline downloads, and to the study record a pipeline is given, before anything
reaches a worker's working directory.

Kept, because inference needs them and they are not Safe Harbor identifiers: modality and
acquisition parameters, pixel data, sex, age (except 90+, grouped), weight and height
(SUV), times of day (decay correction), descriptions of the study/series/protocol, and the
DICOM UIDs. UIDs are generated by the modality, not derived from patient information, and
serve as the platform's internal re-identification code (164.514(c)) — results are linked
back to the patient only by the task, never by the worker.

Dates are not removed but *shifted*: every date in the file moves by the same offset so the
study date becomes 1 January of its year. Intervals (injection → scan, prior → current)
are preserved; no real date other than the year leaves the boundary.
"""

