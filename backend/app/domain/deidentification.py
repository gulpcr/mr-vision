AGE_CAP_YEARS = 90  # Safe Harbor: ages over 89 aggregated into "90 or older"


def cap_age(age: str | None) -> str | None:
    """DICOM AS value ("045Y", "011M") with ages above 89 years reported as 090Y."""
    if not age:
        return age
    text = age.strip().upper()
    if text.endswith("Y") and text[:-1].isdigit() and int(text[:-1]) >= AGE_CAP_YEARS:
        return f"{AGE_CAP_YEARS:03d}Y"
    return text


